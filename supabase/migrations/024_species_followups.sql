-- ============================================================================
-- MIGRATION: Species follow-ups (admin)
-- ============================================================================
-- A to-do list of sources worth chasing for more detail: a book that describes
-- a species properly, a paper behind a paywall, an author to contact, a gap in
-- the data. Shown and edited at /admin/follow-ups, and counted on each row of
-- the species tracker.
--
-- species_followups
--   taxa        who it is about: one or more names. A scientific name applies
--               to that taxon and, for a species, to its subspecies. A genus
--               on its own ("Terrapene") applies to everything in the genus.
--   kind        book | paper | contact | data | other
--   status      open (still to get) | obtained (in hand, not yet used) |
--               done (used in the profile) | dropped
--
-- Only admins can read or change it (profiles.role = 'admin').
--
-- The two notes already kept in future_turtle_resources are copied in. That
-- table is left as it is.
--
-- Requires 017 (is_admin) and 019 (species checklist and progress view).
-- Safe to run more than once.
-- ============================================================================

create table if not exists public.species_followups (
  id bigint generated by default as identity primary key,
  taxa text[] not null
    constraint species_followups_taxa_not_empty check (cardinality(taxa) > 0),
  kind text not null default 'book'
    constraint species_followups_kind_check check (kind in ('book', 'paper', 'contact', 'data', 'other')),
  title text not null
    constraint species_followups_title_not_blank check (btrim(title) <> ''),
  would_fill text,
  url text,
  status text not null default 'open'
    constraint species_followups_status_check check (status in ('open', 'obtained', 'done', 'dropped')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint species_followups_kind_title_key unique (kind, title)
);

comment on table public.species_followups is
  'Sources and gaps to follow up for species profiles (books, papers, contacts). Admin only.';
comment on column public.species_followups.taxa is
  'Scientific names it applies to. A species also covers its subspecies; a bare genus covers the whole genus.';

create index if not exists idx_species_followups_taxa on public.species_followups using gin (taxa);

drop trigger if exists set_updated_at on public.species_followups;
create trigger set_updated_at
  before update on public.species_followups
  for each row execute function public.handle_updated_at();

alter table public.species_followups enable row level security;

drop policy if exists "Admins can read follow-ups" on public.species_followups;
create policy "Admins can read follow-ups"
  on public.species_followups for select
  using ((select public.is_admin()));

drop policy if exists "Admins can add follow-ups" on public.species_followups;
create policy "Admins can add follow-ups"
  on public.species_followups for insert
  with check ((select public.is_admin()));

drop policy if exists "Admins can change follow-ups" on public.species_followups;
create policy "Admins can change follow-ups"
  on public.species_followups for update
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Admins can delete follow-ups" on public.species_followups;
create policy "Admins can delete follow-ups"
  on public.species_followups for delete
  using ((select public.is_admin()));

revoke all on table public.species_followups from anon, authenticated;
grant select, insert, update, delete on table public.species_followups to authenticated;
grant all on table public.species_followups to service_role;
grant usage, select on sequence public.species_followups_id_seq to authenticated, service_role;

-- ----------------------------------------------------------------------------
-- Carry over the notes kept so far in future_turtle_resources
-- ----------------------------------------------------------------------------
insert into public.species_followups (taxa, kind, title, url, notes)
select
  array[coalesce(s.species_scientific_name, r.relevant_species)],
  case when r.notes ilike '%contact author%' then 'contact' else 'paper' end,
  'Earlier note for ' || r.relevant_species || ' (' || r.created_at::date || ')',
  substring(r.notes from 'https?://[^\s]+'),
  -- the note itself, unless it was nothing but that one link
  nullif(btrim(regexp_replace(r.notes, '\s+', ' ', 'g')), substring(r.notes from 'https?://[^\s]+'))
from public.future_turtle_resources r
left join public.turtle_species s on s.species_common_name = r.relevant_species
on conflict (kind, title) do nothing;

-- ----------------------------------------------------------------------------
-- Progress view: same as before, plus the number of follow-ups still pending
-- ----------------------------------------------------------------------------
create or replace view public.admin_species_progress
with (security_invoker = true)
as
select
  c.id                                          as checklist_id,
  coalesce(c.scientific_name, s.species_scientific_name) as scientific_name,
  c.taxon_rank,
  c.parent_species,
  c.genus,
  coalesce(fam.family_scientific_name, c.family) as family,
  fam.family_common_name                        as family_common_name,
  c.common_name                                 as checklist_common_name,
  c.conservation_status,
  c.cites_appendix,
  c.continents,
  c.source,
  c.skip_reason,
  c.notes,

  s.id                                          as species_id,
  s.slug,
  s.species_common_name,
  s.species_scientific_name                     as profile_scientific_name,
  s.status                                      as profile_status,
  s.created_at                                  as profile_created_at,
  s.limited_information_toggle                  as limited_information,

  case
    when s.id is not null and s.status = 'published' then 'published'
    when s.id is not null                            then 'draft'
    when c.skip_reason is not null                   then 'skipped'
    else 'not_started'
  end                                           as tracking_status,

  (s.avatar_image_circle_url is not null and s.avatar_image_full_url is not null) as has_avatar,
  coalesce((
    select num_nonnulls(
      nullif(btrim(d.at_a_glance), ''), nullif(btrim(d.identification), ''),
      nullif(btrim(d.distribution), ''), nullif(btrim(d.habitat), ''),
      nullif(btrim(d.diet), ''), nullif(btrim(d.hibernation), ''),
      nullif(btrim(d.nesting), ''), nullif(btrim(d.unique_traits_and_qualities), ''),
      nullif(btrim(d.conservation), ''), nullif(btrim(d.predators), ''),
      nullif(btrim(d.threats), ''))
    from public.turtle_species_section_descriptions d
    where d.species_id = s.id
    order by d.created_at
    limit 1
  ), 0)                                         as text_sections_filled,
  coalesce((
    select num_nonnulls(
      m.adult_weight, m.length_female_max_scl, m.length_male_max_scl, m.generally_larger,
      m.lifespan_wild_min, m.lifespan_wild_max, m.lifespan_captivity_min, m.lifespan_captivity_max)
    from public.turtle_species_measurements m
    where m.species_id = s.id
    order by m.created_at
    limit 1
  ), 0)                                         as measurements_filled,
  (select count(*) from public.turtle_species_conservation_history x where x.species_id = s.id)        as conservation_rows,
  (select count(*) from public.turtle_species_population_estimate_history x where x.species_id = s.id) as population_rows,
  (select count(*) from public.turtle_species_habitats x where x.species_id = s.id)                    as habitat_tags,
  (select count(*) from public.turtle_species_ecologies x where x.species_id = s.id)                   as ecology_tags,
  (select count(*) from public.turtle_species_habitat_types x where x.species_id = s.id)               as habitat_type_tags,
  (select count(*) from public.turtle_species_regions_general x where x.species_id = s.id)             as region_tags,
  (select count(*) from public.turtle_species_threats x where x.species_id = s.id)                     as threat_tags,
  (select count(*) from public.turtle_species_behaviors_general x where x.species_id = s.id)           as behavior_tags,
  (select count(*) from public.turtle_species_references x where x.species_id = s.id)                  as reference_count,
  (select count(*) from public.turtle_species_physical_features_new x where x.species_id = s.id)       as physical_feature_variants,
  exists (select 1 from public.turtle_species_range_maps x where x.species_id = s.id)                  as has_range_map,
  exists (select 1 from care_guides.care_guides g
          where g.species_id = s.id and g.status = 'published')                                        as has_published_care_guide,

  -- New in 024: follow-ups still pending (open or obtained) for this taxon,
  -- its parent species or its genus.
  (select count(*)
   from public.species_followups f
   where f.status in ('open', 'obtained')
     and (c.scientific_name = any (f.taxa)
          or c.parent_species = any (f.taxa)
          or c.genus = any (f.taxa)))                                                                  as pending_followups
from public.species_checklist c
full join public.turtle_species s on s.id = c.turtle_species_id
left join lateral (
  select f.family_scientific_name, f.family_common_name
  from public.turtle_taxonomy_genuses g
  join public.turtle_taxonomy_families f on f.id = g.tax_parent_family
  where g.genus_scientific_name = coalesce(c.genus, split_part(s.species_scientific_name, ' ', 1))
  limit 1
) fam on true;

comment on view public.admin_species_progress is
  'Checklist entries joined to their Turterra profile with per-section entry counts and pending follow-ups. Used by /admin/species.';

revoke all on table public.admin_species_progress from anon, authenticated;
grant select on table public.admin_species_progress to authenticated;
grant select on table public.admin_species_progress to service_role;
