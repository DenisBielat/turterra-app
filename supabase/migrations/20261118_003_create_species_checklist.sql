-- ============================================================================
-- MIGRATION: Species checklist + progress view (admin species tracker)
-- ============================================================================
-- species_checklist     One row per recognised turtle taxon (species or
--                       subspecies): the reference list we work through.
--                       Seeded from the Turtle Conservancy "Turtles of the
--                       World" list (names, taxonomy and status only) by
--                       supabase/content/species_checklist_seed.sql.
--                       A row links to its Turterra profile through
--                       turtle_species_id once the profile exists.
--
-- admin_species_progress  One row per checklist entry joined to its profile,
--                       with counts of what has been entered in each section.
--                       Always computed from the real tables, so it cannot go
--                       stale. Powers /admin/species.
--
-- Requires 20261118_001 (is_admin) and 20261118_002 (turtle_species.status).
-- Safe to run more than once.
-- ============================================================================

create table if not exists public.species_checklist (
  id bigint generated by default as identity primary key,

  -- The taxon
  scientific_name text not null unique,        -- binomial, or trinomial for a subspecies
  taxon_rank text not null
    constraint species_checklist_rank_check check (taxon_rank in ('species', 'subspecies')),
  parent_species text,                         -- binomial of the parent species (subspecies only)
  genus text not null,
  family text,                                 -- as given by the source
  subfamily text,
  superfamily text,
  suborder text,
  common_name text,

  -- Status, as given by the source
  conservation_status text,                    -- IUCN Red List category, or TFTSG provisional where IUCN has none
  iucn_red_list text,
  tftsg_provisional text,
  cites_appendix text,
  continents text[],                           -- AF, AS, AU, EU, NA, OC, SA

  -- Where the row came from
  source text not null,
  source_record_id text,
  source_retrieved_on date,

  -- Turterra tracking
  turtle_species_id bigint unique references public.turtle_species (id) on delete set null,
  skip_reason text,                            -- set when we have decided not to write this one up (yet)
  notes text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.species_checklist is
  'Reference list of recognised turtle taxa, used to track which species have a Turterra profile.';

create index if not exists idx_species_checklist_family on public.species_checklist (family);
create index if not exists idx_species_checklist_parent on public.species_checklist (parent_species);

drop trigger if exists set_updated_at on public.species_checklist;
create trigger set_updated_at
  before update on public.species_checklist
  for each row execute function public.handle_updated_at();

alter table public.species_checklist enable row level security;

-- Internal working list: only admins can read it. There are no write policies,
-- so changes go through SQL files / the service role, like the rest of the
-- species content.
drop policy if exists "Admins can read the species checklist" on public.species_checklist;
create policy "Admins can read the species checklist"
  on public.species_checklist
  for select
  using ((select public.is_admin()));

-- Explicit privileges, so this does not depend on the project's defaults:
-- signed-in users may read (the policy above narrows that to admins),
-- nobody writes through the API.
revoke all on table public.species_checklist from anon, authenticated;
grant select on table public.species_checklist to authenticated;
grant all on table public.species_checklist to service_role;

-- ----------------------------------------------------------------------------
-- Progress view
-- ----------------------------------------------------------------------------
-- security_invoker = true: the view runs with the permissions of whoever
-- queries it, so the admin-only policy above still applies.
--
-- FULL JOIN: a profile that is not linked to any checklist row still shows up
-- (with the checklist columns empty) instead of silently disappearing.

create or replace view public.admin_species_progress
with (security_invoker = true)
as
select
  c.id                                          as checklist_id,
  coalesce(c.scientific_name, s.species_scientific_name) as scientific_name,
  c.taxon_rank,
  c.parent_species,
  c.genus,
  coalesce(fam.family_scientific_name, c.family) as family,
  fam.family_common_name                        as family_common_name,
  c.common_name                                 as checklist_common_name,
  c.conservation_status,
  c.cites_appendix,
  c.continents,
  c.source,
  c.skip_reason,
  c.notes,

  s.id                                          as species_id,
  s.slug,
  s.species_common_name,
  s.species_scientific_name                     as profile_scientific_name,
  s.status                                      as profile_status,
  s.created_at                                  as profile_created_at,
  s.limited_information_toggle                  as limited_information,

  case
    when s.id is not null and s.status = 'published' then 'published'
    when s.id is not null                            then 'draft'
    when c.skip_reason is not null                   then 'skipped'
    else 'not_started'
  end                                           as tracking_status,

  -- What has been entered (all zero / false when there is no profile yet)
  (s.avatar_image_circle_url is not null and s.avatar_image_full_url is not null) as has_avatar,
  coalesce((
    select num_nonnulls(
      nullif(btrim(d.at_a_glance), ''), nullif(btrim(d.identification), ''),
      nullif(btrim(d.distribution), ''), nullif(btrim(d.habitat), ''),
      nullif(btrim(d.diet), ''), nullif(btrim(d.hibernation), ''),
      nullif(btrim(d.nesting), ''), nullif(btrim(d.unique_traits_and_qualities), ''),
      nullif(btrim(d.conservation), ''), nullif(btrim(d.predators), ''),
      nullif(btrim(d.threats), ''))
    from public.turtle_species_section_descriptions d
    where d.species_id = s.id
    order by d.created_at
    limit 1
  ), 0)                                         as text_sections_filled,   -- out of 11
  coalesce((
    select num_nonnulls(
      m.adult_weight, m.length_female_max_scl, m.length_male_max_scl, m.generally_larger,
      m.lifespan_wild_min, m.lifespan_wild_max, m.lifespan_captivity_min, m.lifespan_captivity_max)
    from public.turtle_species_measurements m
    where m.species_id = s.id
    order by m.created_at
    limit 1
  ), 0)                                         as measurements_filled,    -- out of 8
  (select count(*) from public.turtle_species_conservation_history x where x.species_id = s.id)        as conservation_rows,
  (select count(*) from public.turtle_species_population_estimate_history x where x.species_id = s.id) as population_rows,
  (select count(*) from public.turtle_species_habitats x where x.species_id = s.id)                    as habitat_tags,
  (select count(*) from public.turtle_species_ecologies x where x.species_id = s.id)                   as ecology_tags,
  (select count(*) from public.turtle_species_habitat_types x where x.species_id = s.id)               as habitat_type_tags,
  (select count(*) from public.turtle_species_regions_general x where x.species_id = s.id)             as region_tags,
  (select count(*) from public.turtle_species_threats x where x.species_id = s.id)                     as threat_tags,
  (select count(*) from public.turtle_species_behaviors_general x where x.species_id = s.id)           as behavior_tags,
  (select count(*) from public.turtle_species_references x where x.species_id = s.id)                  as reference_count,
  (select count(*) from public.turtle_species_physical_features_new x where x.species_id = s.id)       as physical_feature_variants,
  exists (select 1 from public.turtle_species_range_maps x where x.species_id = s.id)                  as has_range_map,
  exists (select 1 from care_guides.care_guides g
          where g.species_id = s.id and g.status = 'published')                                        as has_published_care_guide
from public.species_checklist c
full join public.turtle_species s on s.id = c.turtle_species_id
left join lateral (
  -- Prefer Turterra's own genus -> family mapping so the tracker matches the site.
  select f.family_scientific_name, f.family_common_name
  from public.turtle_taxonomy_genuses g
  join public.turtle_taxonomy_families f on f.id = g.tax_parent_family
  where g.genus_scientific_name = coalesce(c.genus, split_part(s.species_scientific_name, ' ', 1))
  limit 1
) fam on true;

comment on view public.admin_species_progress is
  'Checklist entries joined to their Turterra profile with per-section entry counts. Used by /admin/species.';

revoke all on table public.admin_species_progress from anon, authenticated;
grant select on table public.admin_species_progress to authenticated;
grant select on table public.admin_species_progress to service_role;
